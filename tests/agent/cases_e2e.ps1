# End-to-end: a friend clone publishes with the REAL host\publish.ps1, then the REAL agent in host mode
# (XRRFIX_REPO = host clone) installs the change into the host fake GAMMA via the real publish.ps1 -SyncOnly + install.ps1.
# Origin is a bare repo on disk whose path contains EduardHavron/xrRazom-GAMMA-fixes.git (forward slashes) -> no network.

function New-E2EMo2([string]$G, [string]$Origin, [string]$Seed, [string[]]$Names) {
    New-Item -ItemType Directory "$G\mods", "$G\profiles\P" -Force | Out-Null
    W "$G\ModOrganizer.exe" '' -NoBom
    W "$G\ModOrganizer.ini" "[General]`r`nselected_profile=@ByteArray(P)`r`n" -NoBom
    W "$G\profiles\P\modlist.txt" ("# This file was automatically generated by Mod Organizer.`r`n" + (($Names | ForEach-Object { "+$_" }) -join "`r`n") + "`r`n+xrRazom Sync_separator`r`n+Other mod`r`n") -NoBom
    foreach ($n in $Names) {
        Copy-Item -LiteralPath "$Seed\mods\$n" -Destination "$G\mods\$n" -Recurse
        W "$G\mods\$n\meta.ini" "[General]`r`nmodid=0`r`n" -NoBom
    }
    W "$G\mods\Other mod\a.txt" 'x' -NoBom
    Invoke-Git $G clone -q -c core.autocrlf=false $Origin repo | Out-Null
    Set-RepoConfig "$G\repo"
}

TC 'AGT-032 AGT-034 E2E friend publishes with the real publish.ps1, host agent installs it into the host GAMMA' {
    $sb = New-Sandbox
    New-Item -ItemType Directory "$sb\EduardHavron" | Out-Null
    Invoke-Git "$sb\EduardHavron" init -q --bare -b main 'xrRazom-GAMMA-fixes.git' | Out-Null
    $bare = "$sb\EduardHavron\xrRazom-GAMMA-fixes.git"
    $origin = $bare -replace '\\', '/'
    $names = @('zz Фикс Y', 'modA')

    $seed = "$sb\seed"
    New-Item -ItemType Directory "$seed\host", "$seed\installer", "$seed\agent", "$seed\pack" -Force | Out-Null
    Copy-Item "$script:SrcAgent\*" "$seed\agent\"
    Copy-Item (Join-Path $script:RepoRoot 'host\publish.ps1'), (Join-Path $script:RepoRoot 'host\publish.bat') "$seed\host\"
    Copy-Item (Join-Path $script:RepoRoot 'installer\install.ps1') "$seed\installer\"
    W "$seed\.gitattributes" "* -text`n" -NoBom
    foreach ($n in $names) { W "$seed\mods\$n\gamedata\scripts\$($n.Replace(' ', '_')).script" "v1 $n`r`n" -NoBom }
    W "$seed\pack\pack.json" "{`n  `"section`": `"xrRazom Sync`",`n  `"mods`": [`n    `"zz Фикс Y`",`n    `"modA`"`n  ]`n}`n" -NoBom
    Invoke-Git $seed init -q -b main | Out-Null
    Set-RepoConfig $seed
    Invoke-Git $seed remote add origin $origin | Out-Null
    Invoke-Git $seed add -A | Out-Null
    Invoke-Git $seed commit -q -m seed | Out-Null
    Invoke-Git $seed push -q -u origin main | Out-Null

    New-E2EMo2 "$sb\H" $origin $seed $names
    New-E2EMo2 "$sb\F" $origin $seed $names

    # friend edits modA in its MO2 and publishes with the real publish.ps1
    $script_ = "$sb\F\mods\modA\gamedata\scripts\modA.script"
    W $script_ "v2 friend`r`n" -NoBom
    $r = Invoke-Ps -Script "$sb\F\repo\host\publish.ps1" -ArgStr "-NoPrompt -Message 'e2e friend change'" -TimeoutSec 300
    Assert-Equal 0 $r.Code "friend publish exit code. Output:`n$($r.Out)"
    Assert-Equal 'v2 friend' (Invoke-Git $sb --git-dir=$bare show main:mods/modA/gamedata/scripts/modA.script).Trim() 'origin has the friend change'

    # host agent (test mode, host mode forced to the host clone)
    $h = New-AgentHome "$sb\hosthome\xrrfix" "$sb\H"
    $r = Invoke-Agent $h -Env @{ XRRFIX_REPO = "$sb\H\repo" } -TimeoutSec 300
    $log = Get-Log $h
    Assert-Equal 0 $r.Code "agent exit code. Log:`n$log"
    $bytes = [IO.File]::ReadAllBytes("$sb\H\mods\modA\gamedata\scripts\modA.script")
    Assert-Equal 'v2 friend|13|10' (([Text.Encoding]::ASCII.GetString($bytes, 0, $bytes.Length - 2)) + '|' + $bytes[-2] + '|' + $bytes[-1]) 'host MO2 got the change byte-exact'
    Assert-PathExists "$sb\H\mods\modA\meta.ini" 'meta.ini kept'
    Assert-Equal "v1 zz Фикс Y" ([IO.File]::ReadAllText("$sb\H\mods\zz Фикс Y\gamedata\scripts\zz_Фикс_Y.script")).Trim() 'untouched mod kept'
    Assert-Match $log (Esc "Режим хоста: клон репозитория $sb\H\repo") 'host mode'
    Assert-Match $log (Esc 'Синхронизация: установлено 1 (modA).') 'sync result'
    Assert-Match $log (Esc '[тест] уведомление: xrRazom fixes | Фиксы xrRazom обновлены: modA') 'notification'
    Assert-Match ([IO.File]::ReadAllText("$h\sync_last.log")) (Esc 'XRRFIX_SYNC_RESULT: installed=1 mods=modA') 'sync_last.log has the real result line'
    Assert-Equal (Invoke-Git $sb --git-dir=$bare rev-parse main).Trim() (Invoke-Git "$sb\H\repo" rev-parse HEAD).Trim() 'host clone fast-forwarded to origin'
    Assert-Match ([IO.File]::ReadAllText("$sb\H\profiles\P\modlist.txt")) '\+Other mod' 'foreign mod still in modlist'

    # second tick: nothing new -> silent
    $before = Get-Log $h
    $r = Invoke-Agent $h -Env @{ XRRFIX_REPO = "$sb\H\repo" } -TimeoutSec 300
    Assert-Equal 0 $r.Code 'second tick exit code'
    Assert-Equal 0 @(Get-Records (Get-NewLog $h $before)).Count 'second tick is silent'
}
